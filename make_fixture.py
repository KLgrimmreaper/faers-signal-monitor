"""Build the committed fixture database for the EU-ADR regression check.

The fixture is not meant to resemble real FAERS data. It is meant to make the evaluation
deterministic and offline: a fixed set of reports where each reference pair is either
clearly enriched or clearly not, so recall, specificity and AUC can be asserted exactly.
Real data has its own numbers, and they are in the README.

    python make_fixture.py

Writes fixtures/euadr_fixture.sql. Run it after changing the reference set.
"""

import csv
import pathlib

from evaluate import OUTCOME_TERMS

HERE = pathlib.Path(__file__).parent
REFERENCE = HERE / "fixtures" / "euadr_reference_set.csv"
TARGET = HERE / "fixtures" / "euadr_fixture.sql"

# background reports, none of them a reference drug. these set the marginal rates, which
# is what makes the enriched pairs stand out
BACKGROUND_REPORTS = 1200
BACKGROUND_DRUG = "ASPIRIN"
BACKGROUND_TERM = "NAUSEA"        # a filler reaction, not one of the outcome terms
BACKGROUND_OUTCOME_EVERY = 40     # one background report in 40 carries each outcome term
BACKGROUND_PREFIX = "bg"

DRUG_REPORTS = 20                 # every reference drug appears in this many reports
STRONG = 18                       # enriched: 18 of the 20 reports carry the outcome term
WEAK = 0                          # not enriched: the drug adds nothing to the background

# which pairs are enriched. every tenth positive is left weak and every fifth negative is
# made strong, so the ranking is imperfect and the AUC is a number rather than 1
POSITIVE_EVERY = 10
NEGATIVE_EVERY = 5


def outcome_terms():
    """The reaction term used for each reference outcome, one per outcome.

    The first term the evaluation would match is enough, and using one per outcome keeps
    the numbers easy to reason about.
    """
    terms = {}
    with open(REFERENCE, encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            outcome = row["outcomeName"]
            if outcome not in terms:
                terms[outcome] = OUTCOME_TERMS[outcome][0]
    return terms


def read_reference():
    with open(REFERENCE, encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def is_enriched(index, ground_truth):
    if ground_truth == 1:
        return index % POSITIVE_EVERY != 0
    return index % NEGATIVE_EVERY == 0


def build_rows():
    rows = []
    report = 0
    terms = outcome_terms()

    # background reports carry each outcome term once in BACKGROUND_OUTCOME_EVERY, which
    # is what sets the marginal rate for every outcome
    for index in range(BACKGROUND_REPORTS):
        report += 1
        reaction = BACKGROUND_TERM
        if index % BACKGROUND_OUTCOME_EVERY == 0:
            reaction = list(terms.values())[index % len(terms)]
        rows.append((f"{BACKGROUND_PREFIX}{index}", BACKGROUND_DRUG, reaction, True, "20240101"))

    # one block of reports per reference drug
    counts = {1: 0, 0: 0}
    for row in read_reference():
        ground_truth = int(row["groundTruth"])
        index = counts[ground_truth]
        counts[ground_truth] += 1

        drug = row["exposureName"].upper()
        term = terms[row["outcomeName"]]
        carrying = STRONG if is_enriched(index, ground_truth) else WEAK

        for position in range(DRUG_REPORTS):
            report += 1
            reaction = term if position < carrying else BACKGROUND_TERM
            rows.append((f"ref{report}", drug, reaction, True, "20240101"))

    return rows, report


def main():
    rows, total = build_rows()
    print(f"{len(rows):,} event rows over {total:,} reports")

    lines = [
        "-- generated by make_fixture.py, do not edit by hand.",
        "-- a deterministic fixture for the EU-ADR regression check, not real data.",
        "TRUNCATE events;",
        "INSERT INTO events (report_id, drug, drug_raw, reaction, serious, received_date) VALUES",
    ]
    values = [
        f"('{report}', '{drug}', '{drug}', '{reaction}', {str(serious).lower()}, '{date}')"
        for report, drug, reaction, serious, date in rows
    ]
    lines.append(",\n".join(values) + ";")
    lines.append("REFRESH MATERIALIZED VIEW drug_totals;")
    lines.append("REFRESH MATERIALIZED VIEW reaction_totals;")
    lines.append("REFRESH MATERIALIZED VIEW event_totals;")
    lines.append("")

    TARGET.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(HERE)}")


if __name__ == "__main__":
    main()
